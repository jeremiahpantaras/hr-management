import * as XLSX from 'xlsx';
import { describe, expect, it } from 'vitest';

import { buildReport } from '@/domain/report';
import { ACTOR, EMERGENCY, SICK, VACATION, juan2026, makeEmployee } from '@/domain/testFixtures';
import { buildReversalEntry } from '@/domain/ledger';
import { buildWorkbook, workbookToBytes } from '@/utils/excel/buildWorkbook';
import { reportFileName, sanitizeFilePart } from '@/utils/excel/fileName';
import {
  BREAKDOWN_HEADERS,
  SHEET_NAMES,
  SUMMARY_HEADERS,
  TRANSACTION_HEADERS,
  isoToLocalDate,
} from '@/utils/excel/formats';
import type { LeaveTransaction } from '@/types/models';

const GENERATED = new Date(2026, 10, 9, 14, 5);
/** What a spreadsheet reader needs to see formats and column widths. */
const READ_OPTIONS: XLSX.ParsingOptions = {
  type: 'array',
  cellDates: true,
  cellNF: true,
  cellStyles: true,
};
const juan = makeEmployee();

function report(over: { ledger?: LeaveTransaction[]; employeeId?: string | null } = {}) {
  const data = juan2026();
  return buildReport({
    filters: {
      year: 2026,
      employeeId: over.employeeId ?? null,
      leaveTypeId: null,
      includeArchived: true,
    },
    employees: [juan],
    leaveTypes: [VACATION, SICK, EMERGENCY],
    balances: data.balances,
    ledger: over.ledger ?? data.ledger,
    generatedAt: GENERATED,
    generatedBy: 'Maria Santos',
  });
}

/** Writes the workbook to bytes and reads it back — what Excel would see (TC-RPT-14). */
function roundTrip(model = report()) {
  const bytes = workbookToBytes(buildWorkbook(model));
  return XLSX.read(bytes, READ_OPTIONS);
}
const rows = (wb: XLSX.WorkBook, name: string) =>
  XLSX.utils.sheet_to_json<unknown[]>(wb.Sheets[name]!, { header: 1, raw: true, blankrows: false });

describe('workbook structure (TC-RPT-01, TC-RPT-10)', () => {
  it('has four sheets with the exact names, in order', () => {
    expect(roundTrip().SheetNames).toEqual([
      'Report Info',
      'Employee Summary',
      'Leave Breakdown',
      'Transactions',
    ]);
    expect(Object.values(SHEET_NAMES)).toHaveLength(4);
  });
  it('sheet names are ≤ 31 characters and contain none of []:*?/\\', () => {
    for (const name of Object.values(SHEET_NAMES)) {
      expect(name.length).toBeLessThanOrEqual(31);
      expect(name).not.toMatch(/[[\]:*?/\\]/);
    }
  });
  it('headers are exactly as specified in UI §14, in row 1', () => {
    const wb = roundTrip();
    expect(rows(wb, 'Employee Summary')[0]).toEqual([...SUMMARY_HEADERS]);
    expect(rows(wb, 'Leave Breakdown')[0]).toEqual([...BREAKDOWN_HEADERS]);
    expect(rows(wb, 'Transactions')[0]).toEqual([...TRANSACTION_HEADERS]);
    expect(SUMMARY_HEADERS).toEqual([
      'Employee ID',
      'Complete Name',
      'Position',
      'Department',
      'Employment Status',
      'Leave Year',
      'Total Leave Credits',
      'Total Leave Used',
      'Total Unused Leave',
      'Record Status',
    ]);
  });
  it('table sheets have an autofilter and set column widths', () => {
    const wb = roundTrip();
    for (const name of ['Employee Summary', 'Leave Breakdown', 'Transactions']) {
      expect(wb.Sheets[name]!['!autofilter']?.ref).toMatch(/^A1:/);
      expect((wb.Sheets[name]!['!cols'] ?? []).length).toBeGreaterThan(0);
    }
  });
});

describe('Juan-2026 content (TC-RPT-02, TC-RPT-14, BR-RPT-01/02)', () => {
  it('Employee Summary row reads 18 / 5 / 13 as real numbers', () => {
    const wb = roundTrip();
    const [, row] = rows(wb, 'Employee Summary');
    expect(row).toEqual([
      'EMP-0042',
      'Juan Dela Cruz',
      'Accounting Staff',
      'Finance',
      'Regular',
      2026,
      18,
      5,
      13,
      'Active',
    ]);
    expect(typeof row?.[6]).toBe('number');
  });
  it('Leave Breakdown rows are 10/3/7, 5/2/3, 3/0/3 and sum to the summary', () => {
    const body = rows(roundTrip(), 'Leave Breakdown').slice(1);
    expect(body.map((r) => [r[3], r[4], r[5], r[6]])).toEqual([
      ['Emergency Leave', 3, 0, 3],
      ['Sick Leave', 5, 2, 3],
      ['Vacation Leave', 10, 3, 7],
    ]);
    expect(body.reduce((t, r) => t + (r[4] as number), 0)).toBe(18);
    expect(body.reduce((t, r) => t + (r[5] as number), 0)).toBe(5);
  });
  it('Report Info states the totals, filters and reconciliation', () => {
    const info = Object.fromEntries(
      rows(roundTrip(), 'Report Info').map((r) => [r[0] as string, r[1]]),
    );
    expect(info).toMatchObject({
      'Report title': 'HR Leave Report',
      'Leave year': 2026,
      'Generated by': 'Maria Santos',
      'Employee filter': 'All employees',
      'Leave type filter': 'All leave types',
      'Include archived': 'Yes',
      'Employees in report': 1,
      'Leave breakdown rows': 3,
      'Transaction rows': 7,
      'Grand total credits': 18,
      'Grand total used': 5,
      'Grand total unused': 13,
      Reconciliation: 'OK',
    });
    expect(info['Generated at']).toBeInstanceOf(Date);
    expect(String(info.Notes)).toContain('no carryover');
  });
  it('round trip: every transaction in the model is in the sheet with equal values', () => {
    const model = report();
    const body = rows(roundTrip(model), 'Transactions').slice(1);
    expect(body).toHaveLength(model.transactions.length);
    model.transactions.forEach((t, i) => {
      const row = body[i]!;
      expect(row[0]).toBe(t.employeeNumber);
      expect(row[3]).toBe(t.leaveType);
      expect(row[4]).toBe(t.transactionType);
      expect(row[7]).toBe(t.days);
      expect(row[12]).toBe(t.effect);
      expect(row[14]).toBe(t.id);
    });
  });
});

describe('cell types and formats (TC-RPT-03/04, BR-RPT-05/07)', () => {
  it('leave dates are real date cells, Date Recorded a date-time, numbers numeric', () => {
    const wb = XLSX.read(workbookToBytes(buildWorkbook(report())), READ_OPTIONS);
    const sheet = wb.Sheets.Transactions!;
    const usageRow = rows(wb, 'Transactions').findIndex((r) => r[5] instanceof Date);
    expect(usageRow).toBeGreaterThan(0);
    const dateFrom = sheet[XLSX.utils.encode_cell({ r: usageRow, c: 5 })] as XLSX.CellObject;
    expect(dateFrom.t).toBe('d');
    expect(dateFrom.z).toBe('yyyy-mm-dd');
    // The file holds 2026-02-10 whatever the machine's time zone (TC-LU-12): check the formatted
    // text and the UTC fields SheetJS reads dates back with.
    expect(dateFrom.w).toBe('2026-02-10');
    expect((dateFrom.v as Date).getUTCFullYear()).toBe(2026);
    expect((dateFrom.v as Date).getUTCMonth()).toBe(1);
    expect((dateFrom.v as Date).getUTCDate()).toBe(10);
    const recorded = sheet[XLSX.utils.encode_cell({ r: usageRow, c: 10 })] as XLSX.CellObject;
    expect(recorded.t).toBe('d');
    expect(recorded.z).toBe('yyyy-mm-dd hh:mm');
    const days = sheet[XLSX.utils.encode_cell({ r: usageRow, c: 7 })] as XLSX.CellObject;
    expect(days.t).toBe('n');
    expect(days.z).toBe('#,##0.0');
  });
  it('a remark of =1+1 stays a literal string cell, never a formula', () => {
    const data = juan2026();
    const ledger = data.ledger.map((e, i) => (i === 0 ? { ...e, remarks: '=1+1' } : e));
    const wb = XLSX.read(workbookToBytes(buildWorkbook(report({ ledger }))), READ_OPTIONS);
    const sheet = wb.Sheets.Transactions!;
    const cell = sheet[XLSX.utils.encode_cell({ r: 1, c: 8 })] as XLSX.CellObject;
    expect(cell.t).toBe('s');
    expect(cell.v).toBe('=1+1');
    expect(cell.f).toBeUndefined();
    const hostile = ['=SUM(A1)', '+1', '-1', '@x', '<script>alert(1)</script>', '😀'];
    hostile.forEach((remark) => {
      const w = roundTrip(
        report({ ledger: data.ledger.map((e, i) => (i === 0 ? { ...e, remarks: remark } : e)) }),
      );
      expect(rows(w, 'Transactions')[1]?.[8]).toBe(remark);
    });
  });
  it('days are always positive and the effect is signed', () => {
    const body = rows(roundTrip(), 'Transactions').slice(1);
    expect(body.every((r) => (r[7] as number) > 0)).toBe(true);
    expect(body.some((r) => (r[12] as number) < 0)).toBe(true);
    expect(body.some((r) => (r[12] as number) > 0)).toBe(true);
  });
  it('half days survive exactly (BR-FR-02)', () => {
    const data = juan2026();
    const ledger = data.ledger.map((e) =>
      e.transactionType === 'USAGE' && e.dateFrom === '2026-04-20'
        ? { ...e, days: 0.5, usedDelta: 0.5 }
        : e,
    );
    const body = rows(roundTrip(report({ ledger })), 'Transactions').slice(1);
    expect(body.some((r) => r[7] === 0.5)).toBe(true);
  });
  it('Status / Reference IDs mark a reversal pair (TC-RPT-06)', () => {
    const data = juan2026();
    const usage = data.ledger.find((e) => e.dateFrom === '2026-04-20')!;
    const built = buildReversalEntry({
      original: usage,
      balance: { totalCredits: 10, totalUsed: 3 },
      reason: 'Oops',
      actor: ACTOR,
    });
    const ledger = [
      ...data.ledger.map((e) =>
        e.id === usage.id ? { ...e, reversedByTransactionId: built.reversalId } : e,
      ),
      { ...built.entry, id: built.reversalId, createdAt: new Date(2026, 8, 1) },
    ];
    const body = rows(roundTrip(report({ ledger })), 'Transactions').slice(1);
    const statuses = body.map((r) => r[13]).filter(Boolean);
    expect(statuses).toContain('Reversed');
    expect(statuses).toContain(`Reversal of ${usage.id}`);
    expect(body.filter((r) => r[5] instanceof Date && r[5].getMonth() === 3)).toHaveLength(2);
  });
});

describe('file names (TC-RPT-09)', () => {
  it('overall and individual names follow the pattern', () => {
    expect(reportFileName(2026, GENERATED)).toBe('HR-Leave-Report_2026_20261109-1405.xlsx');
    expect(reportFileName(2026, GENERATED, 'EMP-0042')).toBe(
      'Leave-Report_EMP-0042_2026_20261109-1405.xlsx',
    );
  });
  it('sanitizes the Employee ID', () => {
    expect(sanitizeFilePart('EMP/../0042 x')).toBe('EMP..0042x');
    expect(sanitizeFilePart('///')).toBe('employee');
    expect(reportFileName(2026, GENERATED, 'a b/c')).toBe(
      'Leave-Report_abc_2026_20261109-1405.xlsx',
    );
  });
});

describe('isoToLocalDate', () => {
  it('keeps the calendar date whatever the zone, including a leap day', () => {
    const d = isoToLocalDate('2028-02-29');
    expect([d.getFullYear(), d.getMonth(), d.getDate()]).toEqual([2028, 1, 29]);
  });
});
