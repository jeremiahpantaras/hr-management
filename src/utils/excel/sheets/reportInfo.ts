import * as XLSX from 'xlsx';

import type { ReportModel } from '@/domain/report';
import { DATETIME_FORMAT, NUMBER_FORMAT } from '@/utils/excel/formats';
import type { Cell } from '@/utils/excel/sheets/sheetHelpers';

/** Key / value sheet (no autofilter, no header row — UI spec §14). */
export function reportInfoSheet(report: ReportModel): XLSX.WorkSheet {
  const { info } = report;
  const aoa: Cell[][] = [
    ['Report title', info.title],
    ['Leave year', info.year],
    ['Generated at', info.generatedAt],
    ['Generated by', info.generatedBy],
    ['Employee filter', info.employeeFilter],
    ['Leave type filter', info.leaveTypeFilter],
    ['Include archived', info.includeArchived ? 'Yes' : 'No'],
    ['Employees in report', info.employeeCount],
    ['Leave breakdown rows', info.breakdownRowCount],
    ['Transaction rows', info.transactionRowCount],
    ['Grand total credits', info.totalCredits],
    ['Grand total used', info.totalUsed],
    ['Grand total unused', info.totalUnused],
    ['Reconciliation', info.reconciliation],
    ['Notes', info.notes],
  ];
  const sheet = XLSX.utils.aoa_to_sheet(aoa, { cellDates: true });
  const format = (row: number, z: string) => {
    const cell = sheet[XLSX.utils.encode_cell({ r: row, c: 1 })] as XLSX.CellObject | undefined;
    if (cell) cell.z = z;
  };
  format(2, DATETIME_FORMAT);
  format(10, NUMBER_FORMAT);
  format(11, NUMBER_FORMAT);
  format(12, NUMBER_FORMAT);
  sheet['!cols'] = [{ wch: 24 }, { wch: 70 }];
  return sheet;
}
